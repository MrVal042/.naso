/** What a manifest with no framework row says the project is, from the manifest alone. */
function genericKind(eco, pkg, ctx) {
  const lang = LANGUAGE_OF[eco];
  if (eco === 'npm') {
    if (pkg?.bin) return { phrase: `${lang} command-line tool (package.json "bin")` };
    if (pkg?.exports) return { phrase: `${lang} library (package.json "exports")` };
    if (pkg?.main) return { phrase: `${lang} library (package.json "main")` };
    return { phrase: `${lang} project` };
  }
  if (eco === 'go') return { phrase: 'Go module', rules: ['goSum'] };
  if (eco === 'cargo') {
    if (ctx.has('src/main.rs')) return { phrase: 'Rust program', rules: ['cargoLock'] };
    if (ctx.has('src/lib.rs')) return { phrase: 'Rust library', rules: ['cargoLock'] };
    return { phrase: 'Rust crate', rules: ['cargoLock'] };
  }
  if (eco === 'maven') return { phrase: 'JVM project', rules: ['gradlew'] };
  return { phrase: `${lang} project` };
}

const article = (phrase) => (/^(?:[aeiou]|npm\b)/i.test(phrase) ? 'an' : 'a');
const capital = (text) => text.charAt(0).toUpperCase() + text.slice(1);

/** One project: a folder with a manifest. */
async function describeProject(cwd, files, ignore, base) {
  const inBase = files.filter((f) => f.startsWith(base));
  const manifests = MANIFEST_NAMES.filter((name) => inBase.includes(base + name));
  if (manifests.length === 0) return null;

  const texts = {};
  for (const name of manifests) texts[name] = await readFile(path.join(cwd, base + name), 'utf8').catch(() => '');
  const parsed = {};
  for (const name of ['package.json', 'composer.json']) {
    if (texts[name] === undefined) continue;
    try {
      parsed[name] = JSON.parse(texts[name]);
    } catch {
      parsed[name] = null;
    }
  }

  const ctx = {
    base,
    files: inBase.map((f) => f.slice(base.length)),
    ignore,
    rel: (p) => base + p,
    has: (p) => inBase.includes(base + p),
    hasDir: (p) => inBase.some((f) => f.startsWith(`${base}${p}/`)),
    uses: (dep) => manifests.some((m) => declares(ECOSYSTEM_OF[m], texts[m], parsed[m], dep)),
  };

  // Python dependencies spread over requirements*.txt too.
  for (const file of inBase.filter((f) => /(?:^|\/)requirements[^/]*\.txt$/.test(f.slice(base.length)) && !manifests.includes(f.slice(base.length)))) {
    texts[file.slice(base.length)] = await readFile(path.join(cwd, file), 'utf8').catch(() => '');
  }
  const ecoTexts = (eco) =>
    Object.entries(texts)
      .filter(([name]) => (ECOSYSTEM_OF[name] ?? (/requirements[^/]*\.txt$/.test(name) ? 'pypi' : null)) === eco)
      .map(([name, text]) => ({ name, text, pkg: parsed[name] }));
  const found = (eco, dep) => ecoTexts(eco).find((entry) => declares(eco, entry.text, entry.pkg, dep));

  let row = null;
  let source = null;
  for (const candidate of FRAMEWORKS) {
    const hit = found(candidate.eco, candidate.dep);
    if (hit) {
      row = candidate;
      source = hit.name;
      break;
    }
  }

  const also = ALSO.filter((entry) => (!entry.with || (row && entry.with.includes(row.name))) && found(entry.eco, entry.dep))
    .filter((entry, i, all) => all.findIndex((other) => other.name === entry.name) === i)
    .filter((entry) => !row || entry.name !== row.name);

  let phrase;
  let ruleNames;
  if (row) {
    phrase = `${row.name} ${row.kind}`;
    const names = [...(row.label ? [row.label] : []), ...also.filter((entry) => !entry.rules).map((entry) => entry.name)];
    if (names.length > 0) phrase += ` (${names.join(', ')})`;
    ruleNames = row.rules;
  } else {
    const eco = ECOSYSTEM_OF[manifests[0]];
    const generic = genericKind(eco, parsed['package.json'], ctx);
    phrase = generic.phrase;
    ruleNames = generic.rules ?? [];
    source = manifests[0];
  }
  ruleNames = [...ruleNames, ...also.flatMap((entry) => entry.rules ?? [])];

  const goModule = manifests.includes('go.mod') ? texts['go.mod'].match(/^module\s+(\S+)/m)?.[1] ?? null : null;
  const rules = [...new Set(ruleNames)].map((name) => RULES[name](ctx)).filter(Boolean);

  return { base, phrase, source: base + source, goModule, rules };
}

/** Workspace declarations at the root: what makes this a monorepo, and in which tool. */
function workspaceOf(files, rootPkg, pm) {
  if (files.includes('pnpm-workspace.yaml')) return { label: 'pnpm monorepo', evidence: '`pnpm-workspace.yaml`' };
  if (rootPkg?.workspaces) return { label: `${pm} monorepo`, evidence: 'package.json "workspaces"' };
  if (files.includes('go.work')) return { label: 'Go workspace', evidence: '`go.work`' };
  if (files.includes('turbo.json')) return { label: 'Turborepo monorepo', evidence: '`turbo.json`' };
  if (files.includes('nx.json')) return { label: 'Nx monorepo', evidence: '`nx.json`' };
  if (files.includes('lerna.json')) return { label: 'Lerna monorepo', evidence: '`lerna.json`' };
  return null;
}

/** Folders that hold a project of their own: a manifest, at most three levels down, not test data. */
function projectDirs(files) {
  const dirs = new Set();
  for (const file of files) {
    const name = file.slice(file.lastIndexOf('/') + 1);
    if (!MANIFEST_NAMES.includes(name) || !file.includes('/')) continue;
    const dir = file.slice(0, file.lastIndexOf('/') + 1);
    if (dir.split('/').length - 1 > 3) continue;
    if (/(?:^|\/)(?:node_modules|vendor|fixtures?|__fixtures__|testdata|tests?|examples?)\//.test(dir)) continue;
    dirs.add(dir);
  }
  // The outermost only: a package's own nested manifest is part of that package.
  const sorted = [...dirs].sort();
  return sorted.filter((dir) => !sorted.some((other) => other !== dir && dir.startsWith(other)));
}

/**
 * The repository as one sentence, and the rules its stacks make true here.
 *
 * Returns `{ summary, short, rules }`: `summary` is the briefing's "What this is" line,
 * `short` the same without its citation for the setup screen, and `rules` the confirmed
 * rules, each a sentence.
 */
export async function detectStack(cwd, files, { ignore = [], pm = 'npm' } = {}) {
  // A malformed manifest is a fact about the repository, not a reason to stop reading it.
  let rootPkg = null;
  if (files.includes('package.json')) {
    try {
      rootPkg = JSON.parse(await readFile(path.join(cwd, 'package.json'), 'utf8'));
    } catch {
      rootPkg = null;
    }
  }
  const workspace = workspaceOf(files, rootPkg, pm);
  const root = await describeProject(cwd, files, ignore, '');
  const nested = [];
  for (const dir of projectDirs(files).slice(0, 12)) {
    const project = await describeProject(cwd, files, ignore, dir);
    if (project) nested.push(project);
  }
  const rules = [...(root && !workspace ? root.rules : []), ...nested.flatMap((project) => project.rules)];
  const parts = (projects) => projects.map((p) => `\`${p.base}\` is ${article(p.phrase)} ${p.phrase}`).join('; ');

  let short;
  let summary;
  if (workspace && nested.length > 0) {
    short = `${capital(article(workspace.label))} ${workspace.label} of ${nested.length} package${nested.length === 1 ? '' : 's'}`;
    summary = `${capital(article(workspace.label))} ${workspace.label} (${workspace.evidence}) of ${nested.length} package${nested.length === 1 ? '' : 's'}: ${parts(nested)}.`;
  } else if (root) {
    const module = root.goModule ? `, module ${root.goModule}` : '';
    short = `${capital(article(root.phrase))} ${root.phrase}`;
    summary = `${short}${module}, from \`${root.source}\`.`;
    if (nested.length > 0) summary += ` Also here: ${parts(nested)}.`;
  } else if (nested.length > 0) {
    short = `A repository of ${nested.length} project${nested.length === 1 ? '' : 's'}`;
    summary = `${short}: ${parts(nested)}.`;
  } else {
    short = 'No manifest NASO reads';
    summary =
      'No manifest NASO reads (package.json, pyproject.toml, go.mod, Cargo.toml, Gemfile and others), so no stack is named.';
  }
  return { summary, short, rules };
}
