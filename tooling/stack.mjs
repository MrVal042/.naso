// NASO stack — what kind of repository this is, in any ecosystem, and the few rules its
// framework makes true here.
//
// One table, one shape for every ecosystem. A framework is a row: the dependency that names
// it, the kind of project it makes, and rules. A rule is a function of this repository that
// returns a sentence or null, and it returns null unless the repository confirms it: a route
// rule needs the route folder, a "generated" rule needs the ignore line or the file. Adding a
// row never changes how another row renders, and a stack that is not here says nothing.
//
// Only manifests are read: package.json, pyproject.toml, requirements*.txt, Pipfile, go.mod,
// Cargo.toml, Gemfile, pom.xml, build.gradle(.kts), composer.json and pubspec.yaml. Never
// source code, never a credential file.
//
// Zero external dependencies — Node.js core modules only.

import { readFile } from 'node:fs/promises';
import path from 'node:path';

const MANIFEST_NAMES = [
  'package.json',
  'pyproject.toml',
  'requirements.txt',
  'Pipfile',
  'go.mod',
  'Cargo.toml',
  'Gemfile',
  'pom.xml',
  'build.gradle',
  'build.gradle.kts',
  'composer.json',
  'pubspec.yaml',
];

/** Which ecosystem each manifest speaks for. */
const ECOSYSTEM_OF = {
  'package.json': 'npm',
  'pyproject.toml': 'pypi',
  'requirements.txt': 'pypi',
  Pipfile: 'pypi',
  'go.mod': 'go',
  'Cargo.toml': 'cargo',
  Gemfile: 'gem',
  'pom.xml': 'maven',
  'build.gradle': 'maven',
  'build.gradle.kts': 'maven',
  'composer.json': 'composer',
  'pubspec.yaml': 'pub',
};

const LANGUAGE_OF = { npm: 'JavaScript', pypi: 'Python', go: 'Go', cargo: 'Rust', gem: 'Ruby', maven: 'JVM', composer: 'PHP', pub: 'Dart' };

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Does this manifest text declare `name` as a dependency, in its ecosystem's syntax? */
function declares(eco, text, pkg, name) {
  switch (eco) {
    case 'npm':
      return Boolean(pkg?.dependencies?.[name] || pkg?.devDependencies?.[name] || pkg?.peerDependencies?.[name]);
    case 'pypi': {
      // `Django==5.1`, `"django>=5"`, `django = "^5"`; names compare case- and dash-insensitively.
      const loose = escape(name).replace(/[-_]/g, '[-_]');
      return new RegExp(`(?:^|[\\s"'\\[,])${loose}(?:\\s*(?:[<>=~!;,"'\\[\\]]|$))`, 'im').test(text);
    }
    case 'go':
      return new RegExp(`(?:^|\\s)${escape(name)}(?:/v\\d+)?\\s+v\\d`, 'm').test(text);
    case 'cargo':
      return new RegExp(`^\\s*${escape(name)}\\s*=`, 'm').test(text);
    case 'gem':
      return new RegExp(`^\\s*gem\\s+['"]${escape(name)}['"]`, 'm').test(text);
    case 'maven':
      return text.includes(name);
    case 'composer':
      return Boolean(pkg?.require?.[name] || pkg?.['require-dev']?.[name]);
    case 'pub':
      return new RegExp(`^\\s+${escape(name)}\\s*:`, 'm').test(text);
    default:
      return false;
  }
}

// ---------------------------------------------------------------------------
// Rules. Each takes the context of one project and returns a sentence or null.
// ---------------------------------------------------------------------------

const code = (p) => `\`${p}\``;

/** The first of these folders that holds tracked files, relative to the project. */
const firstDir = (ctx, candidates) => candidates.find((dir) => ctx.hasDir(dir)) ?? null;

/** Whether .gitignore ignores a root folder, in any of the usual spellings. */
const ignoresDir = (ctx, name) =>
  ctx.ignore.some((line) => new RegExp(`^/?${escape(ctx.base)}${escape(name)}/?$`).test(line.trim()));

const RULES = {
  expoRoutes(ctx) {
    const dir = firstDir(ctx, ['src/app', 'app']);
    if (!dir || !ctx.uses('expo-router')) return null;
    return `Every file under ${code(ctx.rel(dir) + '/')} is a route (Expo Router). Components, hooks and helpers live outside it.`;
  },
  expoNative(ctx) {
    if (!ignoresDir(ctx, 'ios') || !ignoresDir(ctx, 'android')) return null;
    return (
      'ios/ and android/ are generated by `npx expo prebuild` and ignored (`.gitignore`). Change native settings in ' +
      (ctx.has('app.config.ts') ? code(ctx.rel('app.config.ts')) : ctx.has('app.config.js') ? code(ctx.rel('app.config.js')) : ctx.has('app.json') ? code(ctx.rel('app.json')) : 'the app config') +
      ', never in those folders.'
    );
  },
  expoInstall: () => 'Add native packages with `npx expo install <name>`, which picks the version this Expo SDK supports.',
  expoPublic: () => 'Anything in an `EXPO_PUBLIC_` variable is compiled into the app and readable by whoever has it; never put a secret there.',

  nextApp(ctx) {
    const dir = firstDir(ctx, ['src/app', 'app']);
    return dir
      ? `App Router: folders under ${code(ctx.rel(dir) + '/')} are routes, and the \`page\`, \`layout\` and \`route\` files in them are special.`
      : null;
  },
  nextPages(ctx) {
    const dir = firstDir(ctx, ['src/pages', 'pages']);
    return dir ? `Pages Router: every file under ${code(ctx.rel(dir) + '/')} is a route.` : null;
  },
  nextPublic: () => 'Anything in a `NEXT_PUBLIC_` variable is sent to the browser; never put a secret there.',
  vitePublic: () => 'Anything in a `VITE_` variable is bundled for the browser; never put a secret there.',

  djangoManage: (ctx) => (ctx.has('manage.py') ? `Run Django commands through ${code(ctx.rel('manage.py'))}: \`python manage.py <command>\`.` : null),
  djangoMigrations(ctx) {
    const dirs = [...new Set(ctx.files.filter((f) => /(?:^|\/)migrations\/[^/]+\.py$/.test(f)).map((f) => f.slice(0, f.lastIndexOf('/') + 1)))];
    if (dirs.length === 0) return null;
    const shown = dirs.slice(0, 3).map(code).join(', ');
    return (
      `${dirs.length} migrations ${dirs.length === 1 ? 'folder' : 'folders'} (${shown}${dirs.length > 3 ? ', …' : ''}): ` +
      '`makemigrations` writes them. Add a new migration; never edit one that has been applied.'
    );
  },

  railsSchema: (ctx) => (ctx.has('db/schema.rb') ? `${code(ctx.rel('db/schema.rb'))} is generated from the migrations; never edit it by hand.` : null),
  railsMigrate: (ctx) =>
    ctx.hasDir('db/migrate')
      ? `Add a migration under ${code(ctx.rel('db/migrate') + '/')} with \`bin/rails generate migration\`; never edit one that has been applied.`
      : null,

  laravelArtisan: (ctx) => (ctx.has('artisan') ? `Run framework commands through ${code(ctx.rel('artisan'))}: \`php artisan <command>\`.` : null),

  goSum: (ctx) => (ctx.has('go.sum') ? `${code(ctx.rel('go.sum'))} is maintained by \`go mod tidy\`; never edit it by hand.` : null),
  cargoLock: (ctx) => (ctx.has('Cargo.lock') ? `${code(ctx.rel('Cargo.lock'))} is written by cargo; never edit it by hand.` : null),
  gradlew: (ctx) => (ctx.has('gradlew') ? `Build with ${code(ctx.rel('gradlew'))} (\`./gradlew\`), not a system Gradle, so everyone runs the same version.` : null),
  prisma: (ctx) =>
    ctx.has('prisma/schema.prisma')
      ? `Change ${code(ctx.rel('prisma/schema.prisma'))} and run \`prisma migrate dev\`` +
        (ctx.hasDir('prisma/migrations') ? `; never edit the files under ${code(ctx.rel('prisma/migrations') + '/')}.` : '.')
      : null,
  flutterGenerated(ctx) {
    const generated = ctx.files.filter((f) => /\.g\.dart$|\.freezed\.dart$/.test(f)).length;
    return generated > 0 ? `${generated} generated Dart files (\`*.g.dart\`, \`*.freezed.dart\`) are written by \`build_runner\`; never edit them by hand.` : null;
  },
};

