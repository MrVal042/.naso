// Facts a NestJS service's briefing got wrong: entry point, module system, commit format,
// folder purposes, files not edited by hand, and generated paths the check called missing.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { checkBriefing } from '../tooling/check.mjs';
import { runtimeEntry } from '../tooling/scan.mjs';
import { AGENTS, withRepo, put, read } from './helpers.mjs';

async function seedNestService(dir, git) {
  await put(
    dir,
    'package.json',
    JSON.stringify(
      {
        name: 'acme-api',
        version: '0.1.0',
        scripts: { build: 'nest build', start: 'node dist/main.js', lint: 'eslint .' },
        devDependencies: { typescript: '5.6.0', '@nestjs/cli': '11.0.0' },
      },
      null,
      2,
    ) + '\n',
  );
  await put(dir, 'tsconfig.json', '{\n  // comments are allowed here\n  "compilerOptions": { "module": "nodenext", "strict": true }\n}\n');
  await put(dir, 'nest-cli.json', '{ "sourceRoot": "src" }\n');
  await put(dir, 'eslint.config.mjs', 'export default [];\n');
  await put(dir, 'src/app.ts', 'export function buildApp() {}\n');
  await put(dir, 'src/main.ts', "import { buildApp } from './app';\nbuildApp();\n");
  await put(dir, 'src/config/env.ts', 'export const env = {};\n');
  await put(dir, 'src/database/source.ts', 'export const source = {};\n');
  await put(dir, 'openapi.yaml', 'openapi: 3.1.0\n');
  await put(dir, 'CLAUDE.md', '# Standards\n');
  await put(dir, '.gitignore', 'node_modules/\ndist/\nsrc/gen/\n');
  await put(dir, '.prettierignore', '# Generated by npm run openapi\nopenapi.yaml\n\n# Kept as published by the standards repo\nCLAUDE.md\n');
  await put(
    dir,
    'docs/folder-structure.md',
    '# Folders\n\n```\nsrc/\n├── config/      # Environment config, validated at boot\n├── database/    # TypeORM data source\n└── main.ts      # Starts the service\n```\n',
  );
  await put(dir, 'docs/architecture.md', '| Path | Notes |\n|---|---|\n| `src/config/` | Env / required / yes |\n');
  await git('add', '-A');
  await git('commit', '-qm', 'feat: SCRUM-1: scaffold');
  const subjects = [
    'feat: SCRUM-2: add health check',
    'fix: SCRUM-3: env parsing',
    'feat: SCRUM-4: database source',
    'chore: SCRUM-5: lint config',
    'docs: SCRUM-6: folder structure',
    'chore(SCRUM-40): bump deps',
    'chore(SCRUM-40): bump more deps',
  ];
  for (const subject of subjects) {
    await git('commit', '-q', '--allow-empty', '-m', subject);
  }
}

test('a NestJS service is read as CommonJS from tsconfig, not ES modules from one .mjs config', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const text = await read(dir, AGENTS);
    assert.doesNotMatch(text, /ES modules \(\.mjs/);
    assert.match(text, /CommonJS: tsconfig\.json sets "module": "nodenext"/);
  });
});

test('the entry point is the file nest-cli.json starts, not the first app.ts alphabetically', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const text = await read(dir, AGENTS);
    assert.match(text, /entry `src\/main\.ts` \(nest-cli\.json\)/);
    assert.doesNotMatch(text, /entry `src\/app\.ts`/);
  });
});

test('a Dockerfile CMD or start script is traced from dist/ back to the source file', async () => {
  const files = ['src/app.ts', 'src/main.ts', 'Dockerfile'];
  await withRepo(async ({ dir }) => {
    await put(dir, 'Dockerfile', 'FROM node:22\nCMD ["node", "dist/main.js"]\n');
    assert.deepEqual(await runtimeEntry(dir, files, null), { file: 'src/main.ts', source: 'Dockerfile CMD' });
    assert.deepEqual(await runtimeEntry(dir, ['src/app.ts', 'src/main.ts'], { scripts: { start: 'node dist/main.js' } }), {
      file: 'src/main.ts',
      source: 'package.json "start" script',
    });
    assert.equal(await runtimeEntry(dir, ['src/app.ts'], { scripts: { start: 'nest start' } }), null);
  });
});

test('commit subjects are counted by exact form, so a scoped subject is not counted as ticketed', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const text = await read(dir, AGENTS);
    // 6 ticketed, 2 scoped, and the seed commit `init` plus NASO's none: 9 in all.
    assert.match(text, /Subjects follow `type: SCRUM-n: summary` in 6 of the last 9 non-merge commits/);
    assert.match(text, /Of the rest, 2 use `type\(scope\): summary`, 1 has no type\./);
  });
});

test('folder purposes come from a tree diagram, and a table row is split into cells', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const text = await read(dir, AGENTS);
    assert.match(text, /Environment config, validated at boot/);
    assert.match(text, /TypeORM data source/);
    assert.doesNotMatch(text, /Env \/ required/);
  });
});

test('.prettierignore comments mark files as generated or kept as published', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const text = await read(dir, AGENTS);
    assert.match(text, /`openapi\.yaml` — \.prettierignore says "Generated by npm run openapi"; regenerate it/);
    assert.match(text, /`CLAUDE\.md` — \.prettierignore says "Kept as published by the standards repo"; leave it as it is/);
  });
});

test('a git-ignored path in the briefing is generated, not missing', async () => {
  await withRepo(async ({ dir, git, bare }) => {
    await seedNestService(dir, git);
    assert.equal((await bare(['--yes'])).code, 0);
    const file = path.join(dir, AGENTS);
    const text = await readFile(file, 'utf8');
    await writeFile(
      file,
      text.replace('<!-- naso:end -->', 'Client code in `src/gen/` is generated. Changelog lives in `customer-changelog:changelog/customer/`. Not here: `src/nowhere/`.\n<!-- naso:end -->'),
    );
    const result = await checkBriefing(dir);
    assert.deepEqual(result.missing, ['src/nowhere/']);
    assert.deepEqual(result.ignored, ['src/gen/']);
  });
});
